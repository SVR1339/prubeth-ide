def apply_deep_distinction():
    print("=" * 70)
    print("APPLYING DEEP PRUBETH DISTINCTION ACROSS RUNTIME BUNDLES & ENGINES")
    print("=" * 70)

    for target in TARGET_DIRS:
        if not target.exists():
            print(f"Skipping non-existent directory: {target}")
            continue

        print(f"\nProcessing target: {target}")
        out_dir = target / "out"
        if not out_dir.exists():
            print(f"No 'out' directory in {target}")
            continue

        modified_files = 0
        total_replacements = 0

        for fpath in out_dir.rglob("*"):
            if fpath.is_file() and fpath.suffix in [".js", ".html", ".css", ".json"]:
                try:
                    content = fpath.read_text(encoding="utf-8", errors="ignore")
                    new_content = content
                    file_replacements = 0

                    for src, dst in REPLACEMENTS:
                        if src in new_content:
                            cnt = new_content.count(src)
                            new_content = new_content.replace(src, dst)
                            file_replacements += cnt

                    if new_content != content:
                        fpath.write_text(new_content, encoding="utf-8")
                        modified_files += 1
                        total_replacements += file_replacements
                        print(f"  [PATCHED] {fpath.relative_to(target)} ({file_replacements} replacements)")
                except Exception as e:
                    print(f"  [ERROR] {fpath.name}: {e}")

        print(f"Completed {target.name}: {modified_files} files patched with {total_replacements} total replacements.")

if __name__ == "__main__":
    apply_deep_distinction()
